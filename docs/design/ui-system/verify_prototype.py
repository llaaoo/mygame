"""Validate the standalone concept with real browser events; no Godot claims."""
import argparse
import json
from pathlib import Path
from playwright.sync_api import sync_playwright

parser = argparse.ArgumentParser()
parser.add_argument('--url', default='http://127.0.0.1:8766/docs/design/ui-system/')
parser.add_argument('--out', default='/tmp/grayriver-ui-check')
args = parser.parse_args()
out = Path(args.out)
(out / 'screenshots').mkdir(parents=True, exist_ok=True)
checks, errors, failed_requests = [], [], []

def check(name, condition):
    assert condition, name
    checks.append(name)

with sync_playwright() as p:
    browser = p.chromium.launch(executable_path='/usr/bin/chromium', headless=True, args=['--no-sandbox'])
    page = browser.new_page(viewport={'width': 1440, 'height': 1000}, device_scale_factor=1)
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.on('response', lambda r: failed_requests.append(r.url) if r.status >= 400 else None)
    page.goto(args.url, wait_until='networkidle')
    page.evaluate('document.fonts.ready')
    check('13 independent HUD keys', page.locator('[data-slot]').count() == 13)
    check('E and 1 distinct sources', page.locator('[data-slot="E"]').get_attribute('title') != page.locator('[data-slot="1"]').get_attribute('title'))
    check('ordinary actor has no mana meter', page.locator('.vitals .meter').count() == 2)
    page.keyboard.press('g')
    check('unawakened active spell has no ready forms', page.locator('[data-form]').count() == 0)
    page.keyboard.press('e')
    check('mundane spray remains available', page.locator('[data-form]').count() == 1)
    page.locator('[data-form]').click()
    check('selection never consumes bottle', page.locator('[data-slot="E"] .count').inner_text() == '2剂')
    page.locator('#actor-mode').select_option('awakened')
    check('awake actor shows mana', page.locator('.vitals .meter').count() == 3)
    page.keyboard.press('g'); page.keyboard.press('q')
    check('explicit material and no-material forms coexist', page.locator('[data-form]').count() == 2)
    page.keyboard.press('Escape')
    check('Esc closes selector first', page.locator('#selector').inner_text() == '' and page.locator('#modal').inner_text() == '')
    page.keyboard.press('i')
    before = page.locator('[data-clock]').inner_text()
    page.wait_for_timeout(1150)
    check('demo clock continues in menu', page.locator('[data-clock]').inner_text() != before)
    page.locator('[data-item="bow"]').click()
    page.locator('[data-action="equip"]').click()
    check('paperdoll and source reflect equipped bow', '灰河短弓' in page.locator('[data-value="主手"]').get_attribute('title'))
    page.locator('[data-item="coat"]').click(); page.locator('[data-action="equip"]').click()
    check('unequipped coat removed from silhouette', page.locator('.figure .coat').count() == 0)
    page.locator('[data-item="spray_a"]').click(); page.locator('[data-action="use"]').click()
    check('specific spray dose decrements', '1 / 3' in page.locator('#item-detail').inner_text())
    page.locator('[data-item="spray_b"]').click()
    check('second bottle retains its dose', '3 / 3' in page.locator('#item-detail').inner_text())
    page.locator('[data-action="bind-item"]').click(); page.locator('[data-bind-slot="1"]').click()
    page.keyboard.press('Escape')
    check('rebinding 1 preserves E', 'II' in page.locator('[data-slot="1"]').get_attribute('title') and '· I' in page.locator('[data-slot="E"]').get_attribute('title'))
    page.keyboard.press('k'); page.locator('[data-skill="breaker"]').click(); page.locator('[data-bind-slot="2"]').click()
    check('weapon art cannot occupy action slot', '火抹布' in page.locator('[data-bind-slot="2"]').get_attribute('title'))
    page.keyboard.press('i'); page.locator('#item-search').fill('苦叶')
    check('search filters items', page.locator('[data-item]').count() == 2)
    page.locator('#item-search').fill(''); page.locator('[data-item="spray_b"]').click(button='right')
    page.locator('[data-action="drop-item"]').click(); page.keyboard.press('Escape')
    check('lost source remains bound without replacement', 'II' in page.locator('[data-slot="1"]').get_attribute('title') and page.locator('[data-slot="1"] .count').inner_text() == '失效')
    # Display must mark the missing source, not merely retain its name.
    check('lost source visibly unavailable', 'unavailable' in page.locator('[data-slot="1"]').get_attribute('class'))
    page.locator('[data-demo="character"]').click(); page.locator('[data-action="learn-perk"]').click(); page.locator('[data-action="learn-perk"]').click()
    check('perk cannot charge twice', '0 个可用PERK点' in page.locator('.top-data').inner_text())
    page.locator('[data-demo="craft"]').click(); page.locator('[data-craft="stone"]').click(); page.locator('[data-action="craft"]').click()
    check('sample recipe consumes real mock ingredients', '持有 1' in page.locator('.ingredient').first.inner_text())
    page.locator('[data-action="craft"]').click()
    check('insufficient recipe refuses consumption', '原料不足' in page.locator('#toast').inner_text())
    page.locator('[data-demo="map"]').click()
    original = page.locator('.map-art').get_attribute('viewBox')
    page.locator('.map-art').hover(position={'x': 100, 'y': 100}); page.mouse.wheel(0, -100)
    page.wait_for_timeout(100)
    check('map wheel zoom changes view', original != page.locator('.map-art').get_attribute('viewBox'))
    zoomed = page.locator('.map-art').get_attribute('viewBox')
    page.mouse.down(button='right'); page.mouse.move(350, 410); page.mouse.up(button='right')
    check('map drag changes view', zoomed != page.locator('.map-art').get_attribute('viewBox'))
    page.locator('#threat-demo').click()
    check('danger visible inside menu', page.locator('#danger').is_visible())
    page.keyboard.press('Escape')
    check('danger can return to world in one key', page.locator('#modal').inner_text() == '')
    page.reload(wait_until='networkidle'); page.evaluate('document.fonts.ready')
    for view in ['hud', 'combat', 'inventory', 'skills', 'character', 'journal', 'map', 'craft', 'dialogue', 'settings']:
        page.locator(f'[data-demo="{view}"]').click()
        if view == 'settings': page.wait_for_timeout(2400)
        page.screenshot(path=str(out / 'screenshots' / f'{view}.png'))
    for width, height in [(960,720),(1440,900),(1920,1080)]:
        page.set_viewport_size({'width':width,'height':height})
        page.locator('[data-demo="settings"]').click(); page.locator('#font-setting').select_option('125')
        for view in ['inventory','skills','dialogue','craft','settings','map','hud']:
            page.locator(f'[data-demo="{view}"]').click()
            check(f'{width}x{height} 125% {view} no horizontal overflow', page.evaluate('document.documentElement.scrollWidth <= innerWidth'))
            if view != 'hud':
                button = page.locator('.menu-top [data-action="close"]'); box = button.bounding_box()
                check(f'{width}x{height} {view} return within viewport', box['x']>=0 and box['x']+box['width']<=width and box['y']+box['height']<=height)
        if width==960:
            page.wait_for_timeout(2400)
            page.locator('[data-demo="inventory"]').click();page.screenshot(path=str(out/'screenshots'/'inventory-small-large-text.png'))
    check('no JavaScript runtime errors', not errors)
    check('no missing browser assets', not failed_requests)
    browser.close()
report={'scope':'Standalone HTML design prototype; illustrative state, no Godot gameplay or save verification','browser':'system Chromium, Playwright real mouse/keyboard events','checks_passed':len(checks),'checks':checks,'errors':errors,'failed_requests':failed_requests,'viewports':['1440x1000 standard screenshots','960x720,1440x900,1920x1080 at 125% text']}
(out/'verification.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
print(json.dumps({'passed':len(checks),'out':str(out)},ensure_ascii=False))
